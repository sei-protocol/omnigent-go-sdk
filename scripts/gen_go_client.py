"""Generate the Go SDK's bindings from the checked-in ``openapi.json``.

``openapi.json`` is the source of truth external SDK tooling reads (see
``tests/server/test_openapi_drift.py``, which pins it byte-for-byte to the live
FastAPI app). This script turns it into the two generated files the Go module at
``sdks/go-client`` ships:

- ``models.gen.go`` — the Go types for the schemas this SDK's surface needs,
  emitted by ``oapi-codegen`` (models only: no client, no server, no spec blob).
- ``events.gen.go`` — the sealed ``Event`` interface's membership and the
  ``type``-string dispatch for the 52-member ``ServerStreamEvent`` union,
  derived from that schema's ``discriminator.mapping``.

Generated code is checked in — ``go get`` fetches a module as source with no
build step, so an ungenerated module simply does not compile for consumers —
and this script is the one blessed way to regenerate it. Run it whenever
``openapi.json`` changes and commit the result.

These transformations happen, in this order, in a temp dir that is never
committed:

1. :func:`_prune` narrows the document to the schemas the SDK's exported API is
   built from — the ``$ref`` closure of :data:`_HANDWRITTEN_ROOTS` plus every
   ``ServerStreamEvent`` variant — and empties ``paths``. Generating the whole
   document instead would export 262 types nobody chose, including 46 named
   after FastAPI's path-mangled operationIds. Narrowing cannot hide a spec
   change: the roots are looked up by name (absent ones fail the build), the
   event roots are read from the union's own discriminator, and the closure
   follows ``$ref`` — so a schema gaining a field, or a reference to a new
   schema, still moves the generated bytes and trips ``--check``.
2. :func:`_downgrade` rewrites the 3.2.0 / JSON-Schema-2020-12 document into the
   OAS 3.0 dialect ``oapi-codegen``'s loader (kin-openapi) models.
   :func:`_assert_supported` then checks every surviving schema keyword against
   an allowlist of keywords the downgrade handles and fails closed on anything
   else, so a new JSON-Schema construct stops the build instead of silently
   degrading a Go type. The allowlist constrains keywords, not values: a new
   ``format``, or a genuinely heterogeneous ``anyOf``, still generates whatever
   ``oapi-codegen`` makes of it.
3. :func:`_rename_event_schemas` namespaces any event whose trailing name is
   published under two ``type`` prefixes, so ``response.heartbeat`` cannot
   answer to the bare Go name a reader reaching for ``session.heartbeat`` would
   type.
4. :func:`_sanitize_descriptions` redacts the server's own internals — private
   attribute names, ``.py`` source references, absolute home directories — out
   of the descriptions that become published Go doc comments, and fails closed
   on a variant of one of those three shapes it was not taught. It recognises
   references by shape, so what it does *not* cover is a dotted lowercase module
   path: ``omnigent.runtime.pending_inputs`` is the same shape as the
   wire-visible label key ``omnigent.codex_native.collaboration_mode``, and the
   two cannot be told apart without knowing which names the server publishes.
   Five such paths survive in ten doc comments; see the package README.
5. :func:`_annotate_wire_types` appends each event's wire ``type`` to its doc
   verbatim. It runs *after* the redaction so that what it appends is not
   subject to it: a wire ``type`` is the contract this package documents, and no
   part of it should ever read as an internal reference.
6. :func:`_skip_optional_collection_pointers` marks every array- and map-valued
   schema so an absent one is a nil slice or map rather than ``*[]T`` /
   ``*map[K]V``. Pointer-to-collection is not a Go idiom, and removing it after
   a v1 tag would be a breaking change.
7. :func:`_detach_package_comment` strips the package doc ``oapi-codegen``
   attaches to its header, because the package doc belongs in ``doc.go`` and two
   of them render concatenated.

Pass ``--check`` to verify the committed bindings are up to date without
writing: it regenerates into a temp dir, compares, and exits non-zero if
``openapi.json`` was edited without regenerating. The ``go-client-fresh``
pre-commit hook runs it in this mode. ``--check`` fails closed when
``oapi-codegen`` is absent; see :func:`_check`.

Usage::

    python scripts/gen_go_client.py            # (re)generate in place
    python scripts/gen_go_client.py --check    # verify freshness (CI / hook)
"""

